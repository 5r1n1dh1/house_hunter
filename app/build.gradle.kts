    val fromEnv = providers.environmentVariable("MAPS_API_KEY").orNull
    if (!fromEnv.isNullOrBlank()) return@run fromEnv
    val propsFile = rootProject.file("local.properties")
    if (propsFile.exists()) {
        Properties().apply { propsFile.inputStream().use { load(it) } }.getProperty("MAPS_API_KEY")
    } else {
        null
    }
} ?: ""

